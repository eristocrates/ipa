namespace http.w3id.org.CEON.ontology.resourceODP.slash

open DoxAletheia

module ceon_resourceODP =
    let _namespace_name = "http://w3id.org/CEON/ontology/resourceODP/"

    let _prefix local_name =
        Namespaced_IRI.parse _namespace_name local_name |> NamespacedName

    /// <summary>
    ///   <see href="http://w3id.org/CEON/ontology/resourceODP/0.5/"></see>
    /// </summary>
    let ``_0.5/`` = _prefix "0.5/"
    /// <summary>
    /// Asset is sth that is valuable and useful to be used in activities, or owned by actors.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/Asset"></see></summary>
    let Asset = _prefix "Asset"
    /// <summary>
    /// A batch of objects is a collection of physical objects that are of the same type, e.g. a set of items (product instances) adhering to the same product model.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/BatchOfObjects"></see></summary>
    let BatchOfObjects = _prefix "BatchOfObjects"
    /// <summary>
    /// A physical object is a collection of matter.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/PhysicalObject"></see></summary>
    let PhysicalObject = _prefix "PhysicalObject"
    /// <summary>
    /// hasPhysicalObject intends to represent that a batch of objects or a set of objects can have composing components of physical objects.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasPhysicalObject"></see></summary>
    let hasPhysicalObject = _prefix "hasPhysicalObject"
    /// <summary>
    /// batchSize intends to repsent how many physical objects are belong to a batch of objects.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/batchSize"></see></summary>
    let batchSize = _prefix "batchSize"
    /// <summary>
    /// Asset from which a solution is created or implemented. Depending on the context, reference to “resource” includes “raw material”, “feedstock”, “material” or “component”. Resource includes any energy type (e.g. the energy content or energy potential of materials). Note 4 to entry: Resources can be considered concerning both stocks and flows.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/Resource"></see></summary>
    let Resource = _prefix "Resource"
    /// <summary>
    /// A constituent is a component of object.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/Constituent"></see></summary>
    let Constituent = _prefix "Constituent"
    /// <summary>
    /// A digital object, e.g. a computer file, that is located on some server, hard drive, or on the web. Most often the digital object is the realization of some piece of information.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/DigitalObject"></see></summary>
    let DigitalObject = _prefix "DigitalObject"
    /// <summary>
    /// Information is an abstract concept that represents any kind of interpretations. For instance, information can be data generated by software systems or data used by people for communications.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/Information"></see></summary>
    let Information = _prefix "Information"
    /// <summary>
    /// A matter is a physical substance.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/Matter"></see></summary>
    let Matter = _prefix "Matter"
    /// <summary>
    /// hasConstitutent intends to represent that a physical object can have a collection of composing components.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasConstituent"></see></summary>
    let hasConstituent = _prefix "hasConstituent"
    /// <summary>
    /// hasMatter intends to represent that a physical object can have a collection of matter.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasMatter"></see></summary>
    let hasMatter = _prefix "hasMatter"
    /// <summary>
    /// The status of a resource.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/ResourceCondition"></see></summary>
    let ResourceCondition = _prefix "ResourceCondition"
    /// <summary>
    /// A resource can has specifc conditions.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasResourceCondition"></see></summary>
    let hasResourceCondition = _prefix "hasResourceCondition"
    /// <summary>
    /// The characteristics or attribuets of a resource.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/ResourceProperty"></see></summary>
    let ResourceProperty = _prefix "ResourceProperty"
    /// <summary>
    /// A resource can has specifc properties.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasResourceProperty"></see></summary>
    let hasResourceProperty = _prefix "hasResourceProperty"
    /// <summary>
    /// Resource quality is derived based on assessments of resources considering the conditions and properties.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/ResourceQuality"></see></summary>
    let ResourceQuality = _prefix "ResourceQuality"
    /// <summary>
    /// A resource can has specifc qualities.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasResourceQuality"></see></summary>
    let hasResourceQuality = _prefix "hasResourceQuality"
    /// <summary>
    /// A set of objects is a set of physical objects (items) that can be of different types, i.e. different kinds of items.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/SetOfObjects"></see></summary>
    let SetOfObjects = _prefix "SetOfObjects"
    /// <summary>
    /// hasBatch intends to represent that a set of objects can be captured by a number of batches where each batch contains a number of physical objects.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasBatch"></see></summary>
    let hasBatch = _prefix "hasBatch"
    /// <summary>
    /// identifier for a batch
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/batchID"></see></summary>
    let batchID = _prefix "batchID"
    /// <summary>
    /// label for a batch
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/batchLabel"></see></summary>
    let batchLabel = _prefix "batchLabel"
    /// <summary>
    /// Indicating that some piece of information is contained in a larger collection of information, e.g. a data sheet contains a statement about a certain parameter of a product.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/containsInformation"></see></summary>
    let containsInformation = _prefix "containsInformation"
    /// <summary>
    /// Indicating that something is part of or is contained by something else.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasPart"></see></summary>
    let hasPart = _prefix "hasPart"
    /// <summary>
    /// Defines the location of a resource.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/hasResourceLocation"></see></summary>
    let hasResourceLocation = _prefix "hasResourceLocation"
    /// <summary>
    /// Connecting the information to the object (physical, virtual, imaginary) that the information is about.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/isAbout"></see></summary>
    let isAbout = _prefix "isAbout"
    /// <summary>
    /// Relates a thing, e.g. a digital object, or a physical object, to the information it is a realization of. C.f. a physical book that is the realization of a novel, or a pdf or Excel-file that is a realization of a certain data sheet.
    /// <see href="http://w3id.org/CEON/ontology/resourceODP/isRealizationOf"></see></summary>
    let isRealizationOf = _prefix "isRealizationOf"
