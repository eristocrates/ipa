namespace http.openprovenance.org.model.opmo.hash

open DoxAletheia

module opmo =
    let _namespace_name = "http://openprovenance.org/model/opmo#"

    let _prefix local_name =
        Namespaced_IRI.parse _namespace_name local_name |> NamespacedName

    /// <summary>
    /// A “used” edge from process to an artifact is a relationship intended to indicate that the process required the availability of the artifact to be able to complete its execution. When several artifacts are connected to a same process by multiple “used” edges, all of them were required for the process to complete.
    ///
    /// Used is a class that  encompasses all the properties defined by OPM for this kind of edge. It is a reification of the opmv:used property.
    /// <see href="http://openprovenance.org/model/opmo#Used"></see></summary>
    let Used = _prefix "Used"
    /// <summary>
    /// The serial representation of an artifact Value
    /// <see href="http://openprovenance.org/model/opmo#AValue"></see></summary>
    let AValue = _prefix "AValue"
    /// <summary>
    /// Content of the serial representation of Artifact.
    /// <see href="http://openprovenance.org/model/opmo#content"></see></summary>
    let content = _prefix "content"
    /// <summary>
    /// Denotes how a serialization was constructed. For instance, using the Java bean serializer to create an XML document, by applying a specified transformation to the application data, e.g. anonymisation, by passing a reference to the actual value, or by creating a set of RDF triples.
    /// <see href="http://openprovenance.org/model/opmo#encoding"></see></summary>
    let encoding = _prefix "encoding"
    /// <summary>
    /// The class of all constituents of an OPM graph.
    /// <see href="http://openprovenance.org/model/opmo#Entity"></see></summary>
    let Entity = _prefix "Entity"
    /// <summary>
    /// The class representing an OPM Account.
    /// <see href="http://openprovenance.org/model/opmo#Account"></see></summary>
    let Account = _prefix "Account"
    /// <summary>
    /// The set of OPM entities that can be annotated.
    /// <see href="http://openprovenance.org/model/opmo#Annotable"></see></summary>
    let Annotable = _prefix "Annotable"
    /// <summary>
    /// OPM class used to annotate Annotable entities.
    /// <see href="http://openprovenance.org/model/opmo#Annotation"></see></summary>
    let Annotation = _prefix "Annotation"
    /// <summary>
    /// A (causal) relationship is represented by an arc and denotes the presence of a dependency between the source of the arc (the effect) and the destination of the arc (the cause).
    /// <see href="http://openprovenance.org/model/opmo#Edge"></see></summary>
    let Edge = _prefix "Edge"
    /// <summary>
    /// Node is the class of nodes in an OPM graph. Nodes can be a source or effect of edges.
    /// <see href="http://openprovenance.org/model/opmo#Node"></see></summary>
    let Node = _prefix "Node"
    /// <summary>
    /// The class of all OPM graphs.
    /// <see href="http://openprovenance.org/model/opmo#OPMGraph"></see></summary>
    let OPMGraph = _prefix "OPMGraph"
    /// <summary>
    /// A role designates an artifact’s or agent’s function in a process. Roles are constituents of “used”, “was generated by”, and “was controlled by” edges, aimed at distinguishing the nature of the dependency when multiple such edges are connected to a same process.
    /// <see href="http://openprovenance.org/model/opmo#Role"></see></summary>
    let Role = _prefix "Role"
    /// <summary>
    /// An EventEdge denotes an Edge associated with a time instant.
    /// <see href="http://openprovenance.org/model/opmo#EventEdge"></see></summary>
    let EventEdge = _prefix "EventEdge"
    /// <summary>
    /// A “was generated by” edge from an artifact to a process is a relationship intended to mean that the process was required to initiate its execution for the artifact to have been generated. When several artifacts are connected to a same process by multiple “was generated by” edges, the process had to have begun, for all of them to be generated.
    ///
    /// WasGeneratedBy is a class that  encompasses all the properties defined by OPM for this kind of edge. It is a reification of the opmv:wasGeneratedBy property.
    /// <see href="http://openprovenance.org/model/opmo#WasGeneratedBy"></see></summary>
    let WasGeneratedBy = _prefix "WasGeneratedBy"
    /// <summary>
    /// Observed time.
    /// <see href="http://openprovenance.org/model/opmo#OTime"></see></summary>
    let OTime = _prefix "OTime"
    /// <summary>
    /// Building block allowing for the construction of annotations.  It consists of key-value pair.
    /// <see href="http://openprovenance.org/model/opmo#Property"></see></summary>
    let Property = _prefix "Property"
    /// <summary>
    /// the value of a role or a property
    /// <see href="http://openprovenance.org/model/opmo#value"></see></summary>
    let value = _prefix "value"
    /// <summary>
    /// The effect of a Used edge.
    /// <see href="http://openprovenance.org/model/opmo#effectUsed"></see></summary>
    let effectUsed = _prefix "effectUsed"
    /// <summary>
    /// The role of an edge.
    /// <see href="http://openprovenance.org/model/opmo#role"></see></summary>
    let role = _prefix "role"
    /// <summary>
    /// The cause of a Used edge.
    /// <see href="http://openprovenance.org/model/opmo#causeUsed"></see></summary>
    let causeUsed = _prefix "causeUsed"
    /// <summary>
    /// An edge “was derived from” from artifact A2 to artifact A1 is a relationship that indicates that artifact A1 needs to have been generated for A2 to be generated. The piece of state associated with A2 is dependent on the presence of A1 or on the piece of state associated with A1 .
    ///
    /// WasDerivedFrom is a class that  encompasses all the properties defined by OPM for this kind of edge. It is a reification of the opmv:wasDerivedFrom property.
    /// <see href="http://openprovenance.org/model/opmo#WasDerivedFrom"></see></summary>
    let WasDerivedFrom = _prefix "WasDerivedFrom"
    /// <summary>
    /// An edge “was controlled by” from a process P to an agent Ag is a  dependency that indicates that the start and end of process P was controlled by agent Ag.
    ///
    /// WasControlledBy is a class that  encompasses all the properties defined by OPM for this kind of edge. It is a reification of the opmv:wasControlledBy property.
    /// <see href="http://openprovenance.org/model/opmo#WasControlledBy"></see></summary>
    let WasControlledBy = _prefix "WasControlledBy"
    /// <summary>
    /// An edge “was triggered by” from a process P2 to a process P1 is a causal dependency that indicates that the start of process P1 was required for P2 to be able to complete.
    ///
    /// WasTriggeredBy is a class that  encompasses all the properties defined by OPM for this kind of edge. It is a reification of the opmv:wasTriggeredBy property.
    /// <see href="http://openprovenance.org/model/opmo#WasTriggeredBy"></see></summary>
    let WasTriggeredBy = _prefix "WasTriggeredBy"
    /// <summary>
    /// The effect of a WasControlledBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasControlledBy"></see></summary>
    let effectWasControlledBy = _prefix "effectWasControlledBy"
    /// <summary>
    /// The cause of a WasControlledBy edge.
    /// <see href="http://openprovenance.org/model/opmo#causeWasControlledBy"></see></summary>
    let causeWasControlledBy = _prefix "causeWasControlledBy"
    /// <summary>
    /// The effect of a WasDerivedFrom edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasDerivedFrom"></see></summary>
    let effectWasDerivedFrom = _prefix "effectWasDerivedFrom"
    /// <summary>
    /// The cause of a WasDerivedFrom edge.
    /// <see href="http://openprovenance.org/model/opmo#causeWasDerivedFrom"></see></summary>
    let causeWasDerivedFrom = _prefix "causeWasDerivedFrom"
    /// <summary>
    /// The effect of a WasGeneratedBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasGeneratedBy"></see></summary>
    let effectWasGeneratedBy = _prefix "effectWasGeneratedBy"
    /// <summary>
    /// The cause of a WasGeneratedBy edge.
    /// <see href="http://openprovenance.org/model/opmo#causeWasGeneratedBy"></see></summary>
    let causeWasGeneratedBy = _prefix "causeWasGeneratedBy"
    /// <summary>
    /// The cause of a WasTriggeredBy edge.
    /// <see href="http://openprovenance.org/model/opmo#causeWasTriggeredBy"></see></summary>
    let causeWasTriggeredBy = _prefix "causeWasTriggeredBy"
    /// <summary>
    /// The effect of a WasTriggeredBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasTriggeredBy"></see></summary>
    let effectWasTriggeredBy = _prefix "effectWasTriggeredBy"
    /// <summary>
    /// Object Property to express the member of an OPM entity to some Account.
    /// <see href="http://openprovenance.org/model/opmo#account"></see></summary>
    let account = _prefix "account"
    /// <summary>
    /// Object property to associate an Annotable entity and an Annotation.
    /// <see href="http://openprovenance.org/model/opmo#annotation"></see></summary>
    let annotation = _prefix "annotation"
    /// <summary>
    /// Denotes a serialization of an application value associated with an Artifact. Such serialization should have a type (expressed in a type system suitable for the serialization). Serialization technologies include XML, JSON, and ntriples.
    /// <see href="http://openprovenance.org/model/opmo#avalue"></see></summary>
    let avalue = _prefix "avalue"
    /// <summary>
    /// The cause of an Edge.
    /// <see href="http://openprovenance.org/model/opmo#cause"></see></summary>
    let cause = _prefix "cause"
    /// <summary>
    /// The OPM Ontology offers several data properties that are abbreviation of common properties defined by OPM.
    /// <see href="http://openprovenance.org/model/opmo#datapropertyAbbreviation"></see></summary>
    let datapropertyAbbreviation = _prefix "datapropertyAbbreviation"
    /// <summary>
    /// The effect of an Edge.
    /// <see href="http://openprovenance.org/model/opmo#effect"></see></summary>
    let effect = _prefix "effect"
    /// <summary>
    /// Convenience class introduced to describe the inverse of an effect. It is used to express property chains.
    /// <see href="http://openprovenance.org/model/opmo#effectInverse"></see></summary>
    let effectInverse = _prefix "effectInverse"
    /// <summary>
    /// The cause of a Process by means of a Used edge.
    /// <see href="http://openprovenance.org/model/opmo#effectUsedInverse"></see></summary>
    let effectUsedInverse = _prefix "effectUsedInverse"
    /// <summary>
    /// The cause of a Process by means of a WasControlledBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasControlledByInverse"></see></summary>
    let effectWasControlledByInverse = _prefix "effectWasControlledByInverse"
    /// <summary>
    /// The cause of an Artifact by means of a WasDerivedFrom edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasDerivedFromInverse"></see></summary>
    let effectWasDerivedFromInverse = _prefix "effectWasDerivedFromInverse"
    /// <summary>
    /// The cause of an Artifact by means of a WasGeneratedBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasGeneratedByInverse"></see></summary>
    let effectWasGeneratedByInverse = _prefix "effectWasGeneratedByInverse"
    /// <summary>
    /// The cause of a Process by means of a WasTriggeredBy edge.
    /// <see href="http://openprovenance.org/model/opmo#effectWasTriggeredByInverse"></see></summary>
    let effectWasTriggeredByInverse = _prefix "effectWasTriggeredByInverse"
    /// <summary>
    /// The time at which the agent ended controlling a process.
    /// <see href="http://openprovenance.org/model/opmo#endTime"></see></summary>
    let endTime = _prefix "endTime"
    /// <summary>
    /// The event occurred exactly at this time. This is meant to be an abbreviation for an OTime where noEarlierThan and noLaterThan are identical. exactlyAt should be  disjoint from noLaterThan  U noEarlierThan.
    /// <see href="http://openprovenance.org/model/opmo#exactlyAt"></see></summary>
    let exactlyAt = _prefix "exactlyAt"
    /// <summary>
    /// Property that denotes the constituency relationship between an OPM graph and an account, meaning that the object of this property is an account of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasAccount"></see></summary>
    let hasAccount = _prefix "hasAccount"
    /// <summary>
    /// (Abstract) Property that denotes the constituency relationship between an OPM graph and one of its constituent entity, meaning that the object of this property is a constituent of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasConstituent"></see></summary>
    let hasConstituent = _prefix "hasConstituent"
    /// <summary>
    /// Property that denotes the constituency relationship between an OPM graph and an agent, meaning that the object of this property is an agent of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasAgent"></see></summary>
    let hasAgent = _prefix "hasAgent"
    /// <summary>
    /// Property that denotes the constituency relationship between an OPM graph and an artifact, meaning that the object of this property is an artifact of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasArtifact"></see></summary>
    let hasArtifact = _prefix "hasArtifact"
    /// <summary>
    /// Property that denotes the constituency relationship between an OPM graph and an edge, meaning that the object of this property is an edge of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasDependency"></see></summary>
    let hasDependency = _prefix "hasDependency"
    /// <summary>
    /// Property that denotes the constituency relationship between an OPM graph and a process, meaning that the object of this property is a process of the subject.
    /// <see href="http://openprovenance.org/model/opmo#hasProcess"></see></summary>
    let hasProcess = _prefix "hasProcess"
    /// <summary>
    /// The key of a Property.
    /// <see href="http://openprovenance.org/model/opmo#key"></see></summary>
    let key = _prefix "key"
    /// <summary>
    /// This property provides a human-readable version of an OPM entity.
    /// <see href="http://openprovenance.org/model/opmo#label"></see></summary>
    let label = _prefix "label"
    /// <summary>
    /// the event occurred no earlier than this time
    /// <see href="http://openprovenance.org/model/opmo#noEarlierThan"></see></summary>
    let noEarlierThan = _prefix "noEarlierThan"
    /// <summary>
    /// the event occurred no later than this time
    /// <see href="http://openprovenance.org/model/opmo#noLaterThan"></see></summary>
    let noLaterThan = _prefix "noLaterThan"
    /// <summary>
    /// The persistent name of an entity.  Denotes a persistent name that can be used by OPM graph queriers to compare OPM entities across graphs. The scope of this name is intended to be global.
    /// <see href="http://openprovenance.org/model/opmo#pname"></see></summary>
    let pname = _prefix "pname"
    /// <summary>
    /// This property applies to an OPM graph and denotes a profile that is supported by that graph.
    /// <see href="http://openprovenance.org/model/opmo#profile"></see></summary>
    let profile = _prefix "profile"
    /// <summary>
    /// Object Property that associates an Annotation instance with a (set of) Propery(ies).
    /// <see href="http://openprovenance.org/model/opmo#property"></see></summary>
    let property = _prefix "property"
    /// <summary>
    /// The time at which the agent began controlling a process.
    /// <see href="http://openprovenance.org/model/opmo#startTime"></see></summary>
    let startTime = _prefix "startTime"
    /// <summary>
    /// A piece of timing information associated with an EventEdge.
    /// <see href="http://openprovenance.org/model/opmo#time"></see></summary>
    let time = _prefix "time"
    /// <summary>
    /// The subtype of an entity.
    /// <see href="http://openprovenance.org/model/opmo#type"></see></summary>
    let type_ = _prefix "type"
    /// <summary>
    /// A multi-step used property.
    /// <see href="http://openprovenance.org/model/opmo#usedStar"></see></summary>
    let usedStar = _prefix "usedStar"
    /// <summary>
    /// the transitive closure of wasDerivedFrom
    /// <see href="http://openprovenance.org/model/opmo#wasDerivedFromStar"></see></summary>
    let wasDerivedFromStar = _prefix "wasDerivedFromStar"
    /// <summary>
    /// A multi-step wasGeneratedBy edge.
    /// <see href="http://openprovenance.org/model/opmo#wasGeneratedByStar"></see></summary>
    let wasGeneratedByStar = _prefix "wasGeneratedByStar"
