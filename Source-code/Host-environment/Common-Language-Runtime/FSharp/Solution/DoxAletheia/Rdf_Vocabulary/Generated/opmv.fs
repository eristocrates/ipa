namespace http.purl.org.net.opmv.ns.hash

open DoxAletheia

module opmv =
    let _namespace_name = "http://purl.org/net/opmv/ns#"

    let _prefix local_name =
        Namespaced_IRI.parse _namespace_name local_name |> NamespacedName

    /// <summary>
    /// Agent is a contextual entity acting as a catalyst of a process, enabling, facilitating, controlling, or affecting its execution.
    /// <see href="http://purl.org/net/opmv/ns#Agent"></see></summary>
    let Agent = _prefix "Agent"
    /// <summary>
    /// Process refers to an action or series of actions performed on or caused by artifacts, and resulting in new artifacts.
    /// <see href="http://purl.org/net/opmv/ns#Process"></see></summary>
    let Process = _prefix "Process"
    /// <summary>
    /// Artifact is a general concept that represents immutable piece of state, which may have a physical embodiment in a physical object, or a digital representation in a computer system.
    /// <see href="http://purl.org/net/opmv/ns#Artifact"></see></summary>
    let Artifact = _prefix "Artifact"
    /// <summary>
    /// used is an abstract property to express that an artifact was used by a process.
    /// <see href="http://purl.org/net/opmv/ns#used"></see></summary>
    let used = _prefix "used"
    /// <summary>
    /// wasControlledBy is an abstract property to express that a process was controlled an agent.
    /// <see href="http://purl.org/net/opmv/ns#wasControlledBy"></see></summary>
    let wasControlledBy = _prefix "wasControlledBy"
    /// <summary>
    /// wasDerivedFrom is an abstract property to express that an artifact was derived from another artifact.
    /// <see href="http://purl.org/net/opmv/ns#wasDerivedFrom"></see></summary>
    let wasDerivedFrom = _prefix "wasDerivedFrom"
    /// <summary>
    /// wasEncodedBy is an object property to express that an artifact is encoded by another artifact. The property is useful for expressing the relationship between the data and the file encoding the data.
    /// <see href="http://purl.org/net/opmv/ns#wasEncodedBy"></see></summary>
    let wasEncodedBy = _prefix "wasEncodedBy"
    /// <summary>
    ///
    ///       wasEndedAt is an object property to express that a process was finished at a specific time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Instant" xml:lang="en"&gt;instant&lt;/a&gt;. The property chain defines that all processes, that were performed during a specific time period which ended at a specific instant, were actually finished at that specific time instant.
    ///
    /// <see href="http://purl.org/net/opmv/ns#wasEndedAt"></see></summary>
    let wasEndedAt = _prefix "wasEndedAt"
    /// <summary>
    ///
    ///     wasGeneratedAt is an object property to express that an artifact was generated at a specific time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Instant" xml:lang="en"&gt;instant&lt;/a&gt;. This property is very similar to &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://purl.org/dc/terms/created" xml:lang="en"&gt;dct:created&lt;/a&gt;. Note that in a very fine-grained case the time when an artifact was generated might not be the same as the time when the process producing that artifact finished.
    ///
    /// <see href="http://purl.org/net/opmv/ns#wasGeneratedAt"></see></summary>
    let wasGeneratedAt = _prefix "wasGeneratedAt"
    /// <summary>
    /// wasGeneratedBy is an abstract property to express that an artifact was generated by a process.
    /// <see href="http://purl.org/net/opmv/ns#wasGeneratedBy"></see></summary>
    let wasGeneratedBy = _prefix "wasGeneratedBy"
    /// <summary>
    ///
    ///       wasPerformedAt is an object property to express that a process was performed at a given time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Instant" xml:lang="en"&gt;instant&lt;/a&gt; or during a given time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Interval" xml:lang="en"&gt;interval&lt;/a&gt;.
    ///
    /// <see href="http://purl.org/net/opmv/ns#wasPerformedAt"></see></summary>
    let wasPerformedAt = _prefix "wasPerformedAt"
    /// <summary>
    ///
    ///     wasPerformedBy is an object property to express that a process was performed by an agent. It is a sub-property of &lt;a xmlns="http://www.w3.org/1999/xhtml" href="#wasControlledBy" xml:lang="en"&gt;wasControlledBy&lt;/a&gt;.
    ///
    /// <see href="http://purl.org/net/opmv/ns#wasPerformedBy"></see></summary>
    let wasPerformedBy = _prefix "wasPerformedBy"
    /// <summary>
    ///
    ///       wasStartedAt is an object property to express that a process was started at a given time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Instant" xml:lang="en"&gt;instant&lt;/a&gt;. The property chain defines that all processes, that were performed during a specific time period which began at a specific instant, were actually started at that specific time instant.
    ///
    /// <see href="http://purl.org/net/opmv/ns#wasStartedAt"></see></summary>
    let wasStartedAt = _prefix "wasStartedAt"
    /// <summary>
    /// wasTriggeredBy is an abstract property to express that a process was triggered by another process.
    /// <see href="http://purl.org/net/opmv/ns#wasTriggeredBy"></see></summary>
    let wasTriggeredBy = _prefix "wasTriggeredBy"
    /// <summary>
    ///
    ///     wasUsedAt is an object property to express that an artifact was used at a specific time &lt;a xmlns="http://www.w3.org/1999/xhtml" href="http://www.w3.org/2006/time#Instant" xml:lang="en"&gt;instant&lt;/a&gt;. An artifact might not be used at the starting time of the process that actually consumed it. Hence, we provide a different time-related property to express when an artifact was used.
    /// <see href="http://purl.org/net/opmv/ns#wasUsedAt"></see></summary>
    let wasUsedAt = _prefix "wasUsedAt"
    /// <summary>
    ///
    ///     withRespectOf is an object property to associate a time instant at which an artifact was used or generated with the process that used or generated that artifact. At a very fine-grained distinction, the time when an artifact was used or generated might not be exactly the same as the starting or ending time of the process in which the artifact was involved. The related properties &lt;a xmlns="http://www.w3.org/1999/xhtml" href="#wasUsedAt" xml:lang="en"&gt;opmv:wasUsedAt&lt;/a&gt; and &lt;a xmlns="http://www.w3.org/1999/xhtml" href="#wasGeneratedAt" xml:lang="en"&gt;opmv:wasGeneratedAt&lt;/a&gt; can be used as shortcuts to express time-related information about an artifact. The property  &lt;a xmlns="http://www.w3.org/1999/xhtml" href="#wasUsedAt" xml:lang="en"&gt;opmv:wasUsedAt&lt;/a&gt; is only used when users want to express precisely in which process an artifact was used or generated. It can be omitted in most cases.
    /// <see href="http://purl.org/net/opmv/ns#withRespectOf"></see></summary>
    let withRespectOf = _prefix "withRespectOf"
