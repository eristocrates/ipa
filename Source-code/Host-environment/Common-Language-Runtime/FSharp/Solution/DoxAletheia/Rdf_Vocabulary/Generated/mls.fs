namespace http.www.w3.org.ns.mls.hash

open DoxAletheia

module mls =
    let _namespace_name = "http://www.w3.org/ns/mls#"

    let _prefix local_name =
        Namespaced_IRI.parse _namespace_name local_name |> NamespacedName

    /// <summary>
    /// The algorithm regardless software implementation.
    /// <see href="http://www.w3.org/ns/mls#Algorithm"></see></summary>
    let Algorithm = _prefix "Algorithm"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#InformationEntity"></see>
    /// </summary>
    let InformationEntity = _prefix "InformationEntity"
    /// <summary>
    /// Data is a data item composed of data examples and it may be of a various level of granularity and complexity.
    /// With regard to granularity, it can be a whole dataset (for instance, one main table and possibly other tables), or only a single table, or only a feature (e.g., a column of a table), or only an instance (e.g., row of a table), or a single feature-value pair.
    /// With regard to complexity, data examples are characterized by their datatype, which may be arbitrarily complex (e.g., instead of a table it can be an arbitrary graph).
    /// <see href="http://www.w3.org/ns/mls#Data"></see></summary>
    let Data = _prefix "Data"
    /// <summary>
    /// DataCharacteristic is a distinguishing quality or property that distinguish one data from another.
    /// Such characteristics are often statistical ones (e.g., the number of instances
    /// or the number of features of a data set). They may be also informationtheoretic measures (e.g., class entropy of a categorical data set) or geometric measures of data complexity (e.g., the highest discriminatory power of any single feature in the data set).
    /// <see href="http://www.w3.org/ns/mls#DataCharacteristic"></see></summary>
    let DataCharacteristic = _prefix "DataCharacteristic"
    /// <summary>
    /// A relation between entities and their various characteristics.
    /// <see href="http://www.w3.org/ns/mls#hasQuality"></see></summary>
    let hasQuality = _prefix "hasQuality"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#Quality"></see>
    /// </summary>
    let Quality = _prefix "Quality"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#Dataset"></see>
    /// </summary>
    let Dataset = _prefix "Dataset"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#DatasetCharacteristic"></see>
    /// </summary>
    let DatasetCharacteristic = _prefix "DatasetCharacteristic"
    /// <summary>
    /// EvaluationMeasure is a measure to assess the performance of the model generated by the process that realizes the task. Examples are predictive accuracy or f-measure.
    /// <see href="http://www.w3.org/ns/mls#EvaluationMeasure"></see></summary>
    let EvaluationMeasure = _prefix "EvaluationMeasure"
    /// <summary>
    /// EvaluationProcedure is a technique to evaluate machine learning models. Examples are cross-validation and leave-one-out.
    /// <see href="http://www.w3.org/ns/mls#EvaluationProcedure"></see></summary>
    let EvaluationProcedure = _prefix "EvaluationProcedure"
    /// <summary>
    /// EvaluationProcedure is a technique to evaluate machine learning models. Examples are cross-validation and leave-one-out.
    /// <see href="http://www.w3.org/ns/mls#EvaluationSpecification"></see></summary>
    let EvaluationSpecification = _prefix "EvaluationSpecification"
    /// <summary>
    /// A relation which represents a part-whole relationship holding between an entity and its part.
    /// <see href="http://www.w3.org/ns/mls#hasPart"></see></summary>
    let hasPart = _prefix "hasPart"
    /// <summary>
    /// Task is a formal description of a process that needs to be completed (e.g. based on inputs and outputs). A Task is any piece of work that needs to be addressed in the data mining process. In ML Schema, it is defined based on data.
    /// <see href="http://www.w3.org/ns/mls#Task"></see></summary>
    let Task = _prefix "Task"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#defines"></see>
    /// </summary>
    let defines = _prefix "defines"
    /// <summary>
    /// Experiment is a collection of runs.
    /// <see href="http://www.w3.org/ns/mls#Experiment"></see></summary>
    let Experiment = _prefix "Experiment"
    /// <summary>
    /// Run is an execution of an implementation on a machine (computer). It is limited in time (has a start and end point), can be successful or failed.
    /// <see href="http://www.w3.org/ns/mls#Run"></see></summary>
    let Run = _prefix "Run"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#Process"></see>
    /// </summary>
    let Process = _prefix "Process"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#Feature"></see>
    /// </summary>
    let Feature = _prefix "Feature"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#FeatureCharacteristic"></see>
    /// </summary>
    let FeatureCharacteristic = _prefix "FeatureCharacteristic"
    /// <summary>
    /// Hyperparameter is a prior parameter of an implementation, i.e., a parameter which is set before its execution (e.g. C, the complexity parameter, in weka.SMO).
    /// <see href="http://www.w3.org/ns/mls#HyperParameter"></see></summary>
    let HyperParameter = _prefix "HyperParameter"
    /// <summary>
    /// HyperParameterSetting is an entity which connects a hyperparameter and its value that is being set before an implementation execution.
    /// <see href="http://www.w3.org/ns/mls#HyperParameterSetting"></see></summary>
    let HyperParameterSetting = _prefix "HyperParameterSetting"
    /// <summary>
    ///   <see href="http://www.w3.org/ns/mls#hasValue"></see>
    /// </summary>
    let hasValue = _prefix "hasValue"
    /// <summary>
    /// A relation between an entity and the information content entity that specifies it.
    /// <see href="http://www.w3.org/ns/mls#specifiedBy"></see></summary>
    let specifiedBy = _prefix "specifiedBy"
    /// <summary>
    /// Implementation is an executable implementation of a machine learning algorithm, a script, or a workflow. It is versioned, and sometimes belongs to a library (e.g. WEKA).
    /// <see href="http://www.w3.org/ns/mls#Implementation"></see></summary>
    let Implementation = _prefix "Implementation"
    /// <summary>
    /// A relation between an implementation of a machine learning algorithm and its hyperparameter.
    /// <see href="http://www.w3.org/ns/mls#hasHyperParameter"></see></summary>
    let hasHyperParameter = _prefix "hasHyperParameter"
    /// <summary>
    /// ImplementationCharacteristic is a distinguishing quality or property that distinguish one implementation from another.
    /// <see href="http://www.w3.org/ns/mls#ImplementationCharacteristic"></see></summary>
    let ImplementationCharacteristic = _prefix "ImplementationCharacteristic"
    /// <summary>
    /// A relation between an information entity and a specification that it conforms to.
    /// <see href="http://www.w3.org/ns/mls#implements"></see></summary>
    let implements = _prefix "implements"
    /// <summary>
    /// Model is a generalization of a set of training data able to predict values for unseen instances. It is an output from an execution of a data mining algorithm implementation. Models have a dual nature. They can be treated as data structures and as such represented, stored and manipulated. On the other hand, they act as functions and are executed, taking as input data examples and giving as output the result of applying the function to a data example. Models can also be divided into global or local ones. A global model has global coverage of a data set, i.e., it generalizes the whole data set. A local model, such as a pattern set, is a set of local hypotheses, i.e. each applies to a limited region of the data set.
    /// <see href="http://www.w3.org/ns/mls#Model"></see></summary>
    let Model = _prefix "Model"
    /// <summary>
    /// ModelCharacteristic is a distinguishing quality or property that distinguish one model from another. An example model characetristic may be interpretabilty or a complexity of the model.
    /// <see href="http://www.w3.org/ns/mls#ModelCharacteristic"></see></summary>
    let ModelCharacteristic = _prefix "ModelCharacteristic"
    /// <summary>
    /// ModelEvaluation is a setting of a value of the performance measure  specified by the evaluation specification. It connects a measure specification with its value.
    /// <see href="http://www.w3.org/ns/mls#ModelEvaluation"></see></summary>
    let ModelEvaluation = _prefix "ModelEvaluation"
    /// <summary>
    /// A relation between a run and either a model or model evaluation that is produced on it’s output.
    /// <see href="http://www.w3.org/ns/mls#hasOutput"></see></summary>
    let hasOutput = _prefix "hasOutput"
    /// <summary>
    /// A relation between a run and an algorithm, where the run realizes specifications formulated by the algorithm.
    /// <see href="http://www.w3.org/ns/mls#realizes"></see></summary>
    let realizes = _prefix "realizes"
    /// <summary>
    /// A relation between a run and an implemantation that is being executed during the run.
    /// <see href="http://www.w3.org/ns/mls#executes"></see></summary>
    let executes = _prefix "executes"
    /// <summary>
    /// A relation between a run and data that is taken as input to the run.
    /// <see href="http://www.w3.org/ns/mls#hasInput"></see></summary>
    let hasInput = _prefix "hasInput"
    /// <summary>
    /// A relation between a run and a task, where the run achieves specifications formulated by the task.
    /// <see href="http://www.w3.org/ns/mls#achieves"></see></summary>
    let achieves = _prefix "achieves"
    /// <summary>
    /// Software is implemented computer programs, procedures, scripts or rules with associated documentation, possibly constituting an organized environment, stored in read/write memory for the purpose of being executed within a computer system.
    /// <see href="http://www.w3.org/ns/mls#Software"></see></summary>
    let Software = _prefix "Software"
    /// <summary>
    /// Study is a collection of runs that belong together to do some kind of analysis on its results. This analysis can be general or very specific (e.g. a hypothesis test). Can be linked to files, data, that belong to it.
    /// <see href="http://www.w3.org/ns/mls#Study"></see></summary>
    let Study = _prefix "Study"
    /// <summary>
    /// A relation between a task and either the data or an evaluation specification pertinent to this task.
    /// <see href="http://www.w3.org/ns/mls#definedOn"></see></summary>
    let definedOn = _prefix "definedOn"
