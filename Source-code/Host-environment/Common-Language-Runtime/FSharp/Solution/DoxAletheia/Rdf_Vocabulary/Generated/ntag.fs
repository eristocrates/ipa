namespace http.ns.inria.fr.nicetag._2010._09._09.voc.hash

open DoxAletheia

module ntag =
    let _namespace_name = "http://ns.inria.fr/nicetag/2010/09/09/voc#"

    let _prefix local_name =
        Namespaced_IRI.parse _namespace_name local_name |> NamespacedName

    /// <summary>
    /// Describes the action that is performed whenever resources are aggregated with a collectively defined tag.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Aggregate"></see></summary>
    let Aggregate = _prefix "Aggregate"
    /// <summary>
    /// A super class to describe every tag action as modelled by a named graph according to RDF Graph model (RDFG).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#TagAction"></see></summary>
    let TagAction = _prefix "TagAction"
    /// <summary>
    /// Used to represent the HTTP-accessible realization of an information resource on the Web. The equivalent of irw:WebRepresentation, the Annotated Resource is that which generally triggers the act of tagging. Being dereferenceable by definition, it also provides the address that will be bookmarked on delicious-like sites and work like an anchor for tags. This said, the resource being tagged is in no way limited to HTTP-accessible data (indeed, what supports an act of tagging may very well be what the Web representation represents, a non-information resource for example, instead of the Web representation itself).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#AnnotatedResource"></see></summary>
    let AnnotatedResource = _prefix "AnnotatedResource"
    /// <summary>
    /// Describes the action that is performed with a tag by asking a question.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Ask"></see></summary>
    let Ask = _prefix "Ask"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to assert anything about a resource.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Assert"></see></summary>
    let Assert = _prefix "Assert"
    /// <summary>
    /// Describes tags as automatically generated and/or associated to a resource by a computer.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#AutoTagAction"></see></summary>
    let AutoTagAction = _prefix "AutoTagAction"
    /// <summary>
    /// A collection of tags generated by the users of a given online community or Web service.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#CommunityTagCollection"></see></summary>
    let CommunityTagCollection = _prefix "CommunityTagCollection"
    /// <summary>
    /// Undefined collection of tags.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#TagCollection"></see></summary>
    let TagCollection = _prefix "TagCollection"
    /// <summary>
    /// Used when the sign used to tag is disambiguated.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#DisambiguatedTagAction"></see></summary>
    let DisambiguatedTagAction = _prefix "DisambiguatedTagAction"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to give a notation, a mark of approval and disapproval, or,
    ///   more generally speaking, an evaluation.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Evaluate"></see></summary>
    let Evaluate = _prefix "Evaluate"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to express a feeling, an emotion, etc.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#ExpressFeelings"></see></summary>
    let ExpressFeelings = _prefix "ExpressFeelings"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to define to whom access rights to a resource are granted or denied.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#GiveAccessRights"></see></summary>
    let GiveAccessRights = _prefix "GiveAccessRights"
    /// <summary>
    /// Describes tags whose labels are using the syntax of machine tags as implemented first in Flickr.com.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#MachineTagAction"></see></summary>
    let MachineTagAction = _prefix "MachineTagAction"
    /// <summary>
    /// Describes tags whose labels are following a given syntax for improved precision and tractability.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#SyntacticTagAction"></see></summary>
    let SyntacticTagAction = _prefix "SyntacticTagAction"
    /// <summary>
    /// Describes tags as manually associated to a resource by a human.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#ManualTagAction"></see></summary>
    let ManualTagAction = _prefix "ManualTagAction"
    /// <summary>
    /// Describes tagging involving N-tuple tags (double tags, triple tags, etc.).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#N-TupleTagAction"></see></summary>
    let ``N-TupleTagAction`` = _prefix "N-TupleTagAction"
    /// <summary>
    /// Describes tagging involving N-tuple tags which follow machine tags typed syntax in acontext where Flickr-like APIs are lacking.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#N-TupleTagActionMTS"></see></summary>
    let ``N-TupleTagActionMTS`` = _prefix "N-TupleTagActionMTS"
    /// <summary>
    /// Used to describe an act of tagging performed by the owner of the URI that identifies the tagged resource.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#OwnerTagAction"></see></summary>
    let OwnerTagAction = _prefix "OwnerTagAction"
    /// <summary>
    /// Used to represent the part of the Web representation resource being tagged after the "Point" TagAction is used.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#PartOfWebRepresentation"></see></summary>
    let PartOfWebRepresentation = _prefix "PartOfWebRepresentation"
    /// <summary>
    /// A collection of tags generated by a single user.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#PersonalTagCollection"></see></summary>
    let PersonalTagCollection = _prefix "PersonalTagCollection"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to point to a specific part of a Web representation (the segment of a video,
    ///   a user-generated commentary to a newspaper article, etc.).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Point"></see></summary>
    let Point = _prefix "Point"
    /// <summary>
    /// Describes the action that is performed with a "todo" tag whenever it is used to create a task awaiting performance.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#SetTask"></see></summary>
    let SetTask = _prefix "SetTask"
    /// <summary>
    /// Used to describe an act of tagging performed by a the person who browsed a Web representation.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#VisitorTagAction"></see></summary>
    let VisitorTagAction = _prefix "VisitorTagAction"
    /// <summary>
    /// Describes the action that is performed with a tag whenever it is used to share the representation of a WebResource on various services - Twitter or Delicious for instance - with the owner of a sioc:UserAccount (not necessarily a foaf:Person as it might be either a bot, a person or an institution whose representatives may well vary over time).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#Share"></see></summary>
    let Share = _prefix "Share"
    /// <summary>
    /// Used to represent the resource being tagged. Equivalent of irw:Resource.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#TaggedResource"></see></summary>
    let TaggedResource = _prefix "TaggedResource"
    /// <summary>
    /// Describes tagging involving Web concepts (such as geonames).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#WebConceptTagAction"></see></summary>
    let WebConceptTagAction = _prefix "WebConceptTagAction"
    /// <summary>
    /// Property used to link a single and well individuated TagAction to a TagCollection to account for the various levels of aggregation provided by common tagging applications. There exist different ways to aggregate tags (for instance, http://delicious.com/fabion_gandon/OWL gives a Web representation of all taggings of user "fabien_gandon" involving the tag labeled 'OWL' on delicious.com at time "t").
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#belongsToTagCollection"></see></summary>
    let belongsToTagCollection = _prefix "belongsToTagCollection"
    /// <summary>
    /// Property used when the label of a tag indicates to whom access rights to the tagged resource are conferred.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#canBeReadBy"></see></summary>
    let canBeReadBy = _prefix "canBeReadBy"
    /// <summary>
    /// Used to link a resource to a sign, which can itself, be of any type, provided its representation is HTTP accessible from a URI. NiceTag defines tags by means of a mere property linking two Resources; this said, the many distinctions found in IRW ontology give a more precise account of nt:TaggedResource (see in particular irw:Resource).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isRelatedTo"></see></summary>
    let isRelatedTo = _prefix "isRelatedTo"
    /// <summary>
    /// Property used when the label of a tag indicates to whom access right to the tagged resource are denied.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#cannotBeReadBy"></see></summary>
    let cannotBeReadBy = _prefix "cannotBeReadBy"
    /// <summary>
    /// Property used when a resource elicits an action to be performed.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#elicitsAction"></see></summary>
    let elicitsAction = _prefix "elicitsAction"
    /// <summary>
    /// Corresponds to uses of collectively approved labels shared inside a community.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#hasCommunitySign"></see></summary>
    let hasCommunitySign = _prefix "hasCommunitySign"
    /// <summary>
    /// Property used when the label of a tag indicates the medium which an HTTP-accessible Web representation belongs to ("forum", "video", "photo", "Webpage", "Webservice", etc.).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#hasForMedium"></see></summary>
    let hasForMedium = _prefix "hasForMedium"
    /// <summary>
    /// Property used when the label of a tag indicates which part of a Web representation is being tagged.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#hasPart"></see></summary>
    let hasPart = _prefix "hasPart"
    /// <summary>
    /// Corresponds to uses of user-defined labels that can either serve to gather, categorize, distinguish resources or simply add structure to one's collection of tags.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#hasPersonalSign"></see></summary>
    let hasPersonalSign = _prefix "hasPersonalSign"
    /// <summary>
    /// Property used when the label of a tag describes the topic of a resource.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isAbout"></see></summary>
    let isAbout = _prefix "isAbout"
    /// <summary>
    /// Property used to subsume "isRelevantToSb" and "isRelevantToSt".
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isRelevant"></see></summary>
    let isRelevant = _prefix "isRelevant"
    /// <summary>
    /// Subproperty of 'is relevant to' used to link a resource to the person whom it may be relevant to. In other words, in such a way that no immediate formal link can be inferred between the two except from the point of view of a precise person in addition to the user who defined the said link.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isRelevantToSb"></see></summary>
    let isRelevantToSb = _prefix "isRelevantToSb"
    /// <summary>
    ///   <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isRelevantTo"></see>
    /// </summary>
    let isRelevantTo = _prefix "isRelevantTo"
    /// <summary>
    /// Subproperty of 'is relevant to', used to link a resource to anything that it may be relevant to. In other words, in such a way that no immediate formal link can be inferrend between the two except from the point of view of the creator of the said link.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isRelevantToSt"></see></summary>
    let isRelevantToSt = _prefix "isRelevantToSt"
    /// <summary>
    /// Property used whenever a resource is evaluated, ranked, etc. thanks to a label ("***", "5/10", "0", "best", etc.).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#isWorth"></see></summary>
    let isWorth = _prefix "isWorth"
    /// <summary>
    /// Property used to indicate that the label of a tag denotes/expresses an emotional reaction.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#makesMeFeel"></see></summary>
    let makesMeFeel = _prefix "makesMeFeel"
    /// <summary>
    /// Property used when the label of a tag indicates that a question is being asked.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#raisesQuestionAbout"></see></summary>
    let raisesQuestionAbout = _prefix "raisesQuestionAbout"
    /// <summary>
    /// Corresponds to uses of labels that indicate by whom a resource was suggested.
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#sentBy"></see></summary>
    let sentBy = _prefix "sentBy"
    /// <summary>
    /// Property used when the label of a tag indicates to whom a resource was suggested (models existing features like delicious "for:-username" tags).
    /// <see href="http://ns.inria.fr/nicetag/2010/09/09/voc#sentTo"></see></summary>
    let sentTo = _prefix "sentTo"
